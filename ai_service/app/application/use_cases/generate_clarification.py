def _pick_random_choices(options: List[str], max_count: int = 4) -> List[str]:
    """สุ่มเลือกตัวเลือกไม่เกิน max_count รายการอย่างไดนามิก ไม่ล็อกคำตายตัว (Zero-Hardcode & Dynamic Variety)"""
    if not options:
        return []
    if len(options) <= max_count:
        return list(options)
    return random.sample(options, max_count)

