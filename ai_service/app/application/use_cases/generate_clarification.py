class GenerateClarificationUseCase:
    """Generates structured interactive multi-question questionnaires for underspecified user queries."""

    def __init__(
        self,
        llm_service: LLMServiceInterface,
        item_repo: ItemRepositoryInterface,
        cache_service: CacheServiceInterface
    ):
        self.llm_service = llm_service
        self.item_repo = item_repo
        self.cache_service = cache_service

    def _match_category_taxonomy(self, intent_decision: IntentDecision) -> Optional[Dict]:
        """Matches extracted semantic categories from RouteIntent to taxonomy without regex."""
        if not intent_decision.slots or not intent_decision.slots.categories:
            return None
            
        for extracted_cat in intent_decision.slots.categories:
            # Check exact match or known keys
            if extracted_cat in STORE_CATEGORY_TAXONOMY:
                return STORE_CATEGORY_TAXONOMY[extracted_cat]
            # Match partial category name
            for tax_key in STORE_CATEGORY_TAXONOMY:
                if tax_key in extracted_cat or extracted_cat in tax_key:
                    return STORE_CATEGORY_TAXONOMY[tax_key]
        return None

    def _build_questionnaire(
        self,
        user_message: str,
        tax: Dict,
        intro_message: str,
        missing_dimension: str
    ) -> ClarificationQuestion:
        """Assembles 3-step QuestionStep and ChoiceOption domain models instantly."""
        # Step 1: สุ่มเลือกไม่เกิน 4 ตัวเลือก
        step_1_options = _pick_random_choices(tax["step_1_options"], 4)
        step_1 = QuestionStep(
            id="step_1",
            title=tax["step_1_title"],
            options=step_1_options,
            step=1,
            total_steps=3
        )

        # Step 2: สุ่มเลือกไม่เกิน 4 ตัวเลือกสำหรับ default และ branch
        step_2_options = _pick_random_choices(
            tax.get("step_2_default_options", ["ใช้งานทั่วไป", "ใช้งานระดับมืออาชีพ", "กิจกรรมสันทนาการ"]),
            4
        )
        branch_options = {}
        if tax.get("branch_options"):
            for k, v in tax["branch_options"].items():
                branch_options[k] = _pick_random_choices(v, 4)

        step_2 = QuestionStep(
            id="step_2",
            title=tax["step_2_title"],
            options=step_2_options,
            step=2,
            total_steps=3,
            branch_titles=tax.get("branch_titles"),
            branch_options=branch_options
        )

        # Step 3: คำถามเรื่องงบราคา (4 ตัวเลือก)
        budget_options = _pick_random_choices(
            tax.get("step_3_options", [
                "ตามความเหมาะสม / ไม่จำกัด",
                "ประหยัด (งบสบายกระเป๋า)",
                "มาตรฐาน (คุ้มค่าคุ้มราคา)",
                "ระดับโปร (สเปกพรีเมียม)"
            ]),
            4
        )
        step_3 = QuestionStep(
            id="step_3",
            title=tax.get("step_3_title", "งบประมาณค่าเช่าที่ตั้งไว้ประมาณเท่าไรคะ"),
            options=budget_options,
            step=3,
            total_steps=3
        )

        first_options = [
            ChoiceOption(
                id=f"opt_{idx+1}",
                label=opt,
                action_value=opt
            )
            for idx, opt in enumerate(step_1_options)
        ]

        return ClarificationQuestion(
            question=intro_message,
            options=first_options,
            missing_dimension=missing_dimension,
            original_query=user_message,
            suggested_intent="ITEM_INQUIRY",
            steps=[step_1, step_2, step_3]
        )

    async def _build_comparison_prompt(
        self,
        user_message: str,
        intent_decision: IntentDecision
    ) -> ClarificationQuestion:
        """Prompts the user directly in natural language to type the exact models they wish to compare without choices or questionnaire cards."""
        targets = intent_decision.slots.target_items or []
        target_summary = " และ ".join(targets) if targets else "อุปกรณ์ทั้งสองรายการ"

        prompt = (
            f"ผู้ใช้ต้องการเปรียบเทียบอุปกรณ์ แต่ระบุชื่อรุ่นไม่ชัดเจน (เป็นคำกว้างๆ, ชื่อแบรนด์ลอยๆ หรือคำว่ารุ่นล่าสุด):\n"
            f"คำถามของผู้ใช้: \"{user_message}\"\n"
            f"อุปกรณ์หรือแบรนด์ที่เอ่ยถึง: {target_summary}\n\n"
            f"คำสั่ง: จงเขียนข้อความตอบกลับสั้นๆ 1 ประโยคอย่างสุภาพ นุ่มนวล และเป็นกันเอง เพื่อขอให้คุณลูกค้าพิมพ์ระบุชื่อรุ่นเฉพาะเจาะจงของ {target_summary} ที่ต้องการเปรียบเทียบเข้ามาได้เลย (ไม่ต้องมีแบบสอบถามหรือช้อยส์ตัวเลือก ให้ลูกค้าพิมพ์ระบุเองโดยตรง)\n"
            f"กฎเหล็กสำคัญ:\n"
            f"1. ห้ามยกตัวอย่างชื่อรุ่น และห้ามมีคำว่า 'เช่น' หรือ 'ตัวอย่างเช่น' หรือวงเล็บยกตัวอย่างเด็ดขาด ให้ขอให้คุณลูกค้าระบุชื่อรุ่นเข้ามาตรงๆ\n"
            f"2. เข้าประเด็นทันที ไม่ต้องมีคำทักทายสวัสดีซ้ำซ้อน\n"
            f"3. แชตบอตเป็นผู้หญิง 100% ลงท้ายด้วย 'ค่ะ' หรือ 'นะคะ' เสมอ สั้นกระชับ สละสลวย และห้ามมีตัวอักษรภาษาจีนเด็ดขาด"
        )

        try:
            answer = await self.llm_service.generate_text(
                prompt=prompt,
                system_instruction="คุณเป็นผู้ช่วยของร้านเช่าอุปกรณ์ Yuemnoi ให้ตอบอย่างสุภาพ อบอุ่น และเป็นมืออาชีพ",
                temperature=0.3
            )
            clean_text = sanitize_thai_output(answer).strip()
            clean_text = strip_example_clauses(clean_text)
        except Exception as e:
            logger.warning(f"Error generating comparison clarification prompt: {e}")
            clean_text = ""

        if not clean_text or "เช่น" in clean_text:
            clean_text = f"เพื่อการเปรียบเทียบสเปกที่ชัดเจนและแม่นยำ รบกวนคุณลูกค้าระบุชื่อรุ่นเฉพาะเจาะจงของ {target_summary} ที่ต้องการเปรียบเทียบได้เลยนะคะ"

        return ClarificationQuestion(
            question=clean_text,
            options=[],
            missing_dimension="model_disambiguation",
            original_query=user_message,
            suggested_intent="RENTAL_COMPARISON",
            steps=[]
        )

    async def execute(
        self,
        user_message: str,
        intent_decision: IntentDecision,
        history_context: Optional[str] = None
    ) -> ClarificationQuestion:
        # 0. Comparison Disambiguation Path: Prompt user directly in text to type models
        if intent_decision.is_comparison:
            comp_q = await self._build_comparison_prompt(user_message, intent_decision)
            logger.info("Using text-only comparison clarification (prompting user to type models)")
            return comp_q

        # 1. High-Speed Path: Check if category taxonomy matches extracted semantic slots
        matched_tax = self._match_category_taxonomy(intent_decision)
        if matched_tax:
            target_cat = intent_decision.slots.categories[0] if intent_decision.slots.categories else "อุปกรณ์"
            intro = f"เพื่อช่วยคัดสรร{target_cat}ที่เหมาะกับการใช้งานของคุณที่สุด รบกวนเลือกข้อมูลเพิ่มเติมด้านล่างได้เลยนะคะ"
            logger.info(f"Using category-tailored clarification taxonomy for: {target_cat}")
            return self._build_questionnaire(
                user_message=user_message,
                tax=matched_tax,
                intro_message=intro,
                missing_dimension="usage_and_specs"
            )

        # 2. General Store Path: If vague query across multiple categories
        intro = "เพื่อช่วยค้นหาอุปกรณ์ที่ตรงใจคุณที่สุด รบกวนเลือกข้อมูลด้านล่างได้เลยนะคะ"
        logger.info("Using general store clarification taxonomy with random 4 categories")
        general_tax = dict(GENERAL_STORE_TAXONOMY)
        general_tax["step_1_options"] = _pick_random_choices(GENERAL_STORE_CATEGORIES, 4)
        return self._build_questionnaire(
            user_message=user_message,
            tax=general_tax,
            intro_message=intro,
            missing_dimension="category_and_usage"
        )
